// Stable JSON (PK-sorted rows, fixed key order, money with two decimals) and the one-transaction SQL writer.
import { ERP_TABLES, type ErpTable } from "../../app/schemas/erp";
import type { Row } from "./history-requests";

type Kind = "text" | "money" | "bool";
const T = (names: string): [string, Kind][] => names.split(",").map((n) => [n.trim(), "text"]);
const withMoney = (cols: [string, Kind][], name: string): [string, Kind][] => cols.map(([n, k]) => (n === name ? [n, "money"] : [n, k]));
const withBool = (cols: [string, Kind][], name: string): [string, Kind][] => cols.map(([n, k]) => (n === name ? [n, "bool"] : [n, k]));

export const COLUMNS: Record<ErpTable, [string, Kind][]> = {
  vendor: withBool(T("vendor_id,legal_name,legal_name_norm,is_fictional,uei,registrant_cik,remit_line1,remit_unit,remit_city,remit_state,remit_zip,status,merged_into,legacy_vendor_no,created_at,data_origin"), "is_fictional"),
  vendor_domain: T("vendor_id,domain,added_at,data_origin"),
  vendor_contact: T("contact_id,vendor_id,kind,value,valid_from,valid_to,changed_via,data_origin"),
  vendor_remit_history: T("remit_id,vendor_id,line1,unit,city,state,zip,valid_from,valid_to,changed_via,source_request_id,data_origin"),
  vendor_bank_account: T("bank_account_id,vendor_id,bank_name,routing,account_last4,account_hash,status,changed_at,source_request_id,data_origin"),
  bank_change_request: T("request_id,vendor_id,candidate_vendor_ids,claimed_name,letterhead_name,claimed_remit_line1,claimed_remit_unit,claimed_remit_city,claimed_remit_state,claimed_remit_zip,new_routing,new_account_last4,new_account_hash,sender_domain,reply_to_domain,letter_phones,invoice_refs,received_at,requested_effective,channel,extraction_path,extraction_model,status,data_origin"),
  bank_change_document: T("doc_id,request_id,kind,filename,media_type,sha256,page_count,data_origin"),
  vendor_contact_log: T("log_id,vendor_id,request_id,purpose,phone_e164,phone_source,outcome,called_at,called_by,data_origin"),
  ap_invoice: withMoney(T("invoice_no,vendor_id,amount_usd,invoice_date,status,data_origin"), "amount_usd"),
  payment_run: T("payment_run_id,scheduled_date,cutoff_local,status,data_origin"),
  payment_run_item: withMoney(T("item_id,payment_run_id,vendor_id,invoice_no,bank_account_id,amount_usd,data_origin"), "amount_usd"),
};
const SQL_ORDER: ErpTable[] = ["vendor", "vendor_domain", "vendor_contact", "vendor_remit_history", "vendor_bank_account", "bank_change_request", "bank_change_document", "vendor_contact_log", "ap_invoice", "payment_run", "payment_run_item"];

const jsonValue = (v: Row[string] | undefined, kind: Kind): string => {
  if (v === null || v === undefined) return "null";
  if (kind === "money") return (v as number).toFixed(2);
  return JSON.stringify(v);
};

/** 2-space JSON array; money columns keep two decimals as bare numbers (612400.00). Arrays are sorted by the caller. */
export function tableJson(table: ErpTable, rows: Row[]): string {
  if (rows.length === 0) return "[]\n";
  const cols = COLUMNS[table];
  const body = rows.map((r) => `  {\n${cols.map(([n, k]) => `    ${JSON.stringify(n)}: ${jsonValue(r[n], k)}`).join(",\n")}\n  }`);
  return `[\n${body.join(",\n")}\n]\n`;
}

const sqlValue = (v: Row[string] | undefined, kind: Kind): string => {
  if (v === null || v === undefined) return "NULL";
  if (kind === "money") return (v as number).toFixed(2);
  if (kind === "bool") return v ? "TRUE" : "FALSE";
  return `'${String(v).replace(/'/g, "''")}'`;
};

/** INSERTs in FK order inside one transaction. Merged vendors go last because merged_into references vendor. */
export function seedSql(tables: Record<ErpTable, Row[]>): string {
  const out = ["-- Generated by scripts/gen/make-seed.ts from seed 20261027. Do not edit. Every row is synthetic (data_origin = 'SYNTHETIC').", "BEGIN;"];
  for (const table of SQL_ORDER) {
    const rows = tables[table];
    if (rows.length === 0) continue;
    const cols = COLUMNS[table];
    const head = `INSERT INTO ${table} (${cols.map(([n]) => n).join(", ")}) VALUES`;
    const line = (r: Row): string => `  (${cols.map(([n, k]) => sqlValue(r[n], k)).join(", ")})`;
    if (table === "vendor") {
      const plain = rows.filter((r) => r.merged_into === null);
      const merged = rows.filter((r) => r.merged_into !== null);
      out.push(`${head}\n${plain.map(line).join(",\n")};`);
      if (merged.length > 0) out.push(`${head}\n${merged.map(line).join(",\n")};`);
    } else {
      out.push(`${head}\n${rows.map(line).join(",\n")};`);
    }
  }
  out.push("COMMIT;", "");
  return out.join("\n");
}
export { ERP_TABLES };
